def test_reproducible_plot_scripts_generate_nonempty_pdfs_except_bcc_planes(
    tmp_path: Path,
) -> None:
    """Run reproducible plotting scripts, excluding the known heavy plot jobs."""

    env = os.environ.copy()
    env["MPLBACKEND"] = "Agg"
    env.setdefault("PYTHONHASHSEED", "0")
    env["MPLCONFIGDIR"] = str(tmp_path / "mplconfig")
    env["PYTHON"] = sys.executable

    # Warm the shared Matplotlib cache once so the per-script subprocess
    # timeout tracks plotting work rather than first-import font discovery.
    subprocess.run(
        [sys.executable, "-c", "import matplotlib; import matplotlib.pyplot"],
        check=True,
        capture_output=True,
        text=True,
        env=env,
        timeout=180,
    )

    grouped_rows: dict[str, list[dict[str, str]]] = {}
    for row in reproducible_plot_rows():
        if row["plotting_script"] in HEAVY_SMOKE_EXCLUSIONS:
            continue
        grouped_rows.setdefault(row["plotting_script"], []).append(row)

    for script_rel, rows in grouped_rows.items():
        output_dir = tmp_path / Path(script_rel).stem
        result = subprocess.run(
            [
                sys.executable,
                str(ROOT / script_rel),
                "--output-dir",
                str(output_dir),
            ],
            check=True,
            capture_output=True,
            text=True,
            env=env,
            timeout=180,
        )
        assert result.returncode == 0

        expected_names = sorted(Path(row["generated_output"]).name for row in rows)
        generated_names = sorted(path.name for path in output_dir.glob("*.pdf"))
        assert generated_names == expected_names

        for row in rows:
            generated = output_dir / Path(row["generated_output"]).name
            reference = ROOT / row["included_pdf"]
            assert generated.is_file()
            data = generated.read_bytes()
            assert data.startswith(b"%PDF-")
            size = generated.stat().st_size
            reference_size = reference.stat().st_size
            assert size >= 1500
            assert size >= int(reference_size * 0.05)

        if script_rel == "scripts/reproduce_figures/plot_rank_resolved_103.py":
            sample_pdf = output_dir / expected_names[0]
            text = pdf_strings(sample_pdf)
            assert "w_rank" not in text
            assert "SW+ED" not in text
        if script_rel == "scripts/reproduce_figures/plot_multipole_coefficients.py":
            sample_pdf = output_dir / expected_names[0]
            text = pdf_strings(sample_pdf)
            assert "Q electric" not in text
            assert "M magnetic" not in text
            assert "T magnetic-toroidal" not in text


